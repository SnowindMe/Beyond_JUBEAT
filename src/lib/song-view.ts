// 曲目的「视图」口径：哪些行落在哪个服务器视图、算哪个分区。
// /songs/ 与 /songs/gen/[gen]/ 必须用同一套判断，否则同一个世代在两个页面上的
// 曲数与分区分组会对不上（用户一眼就能看出来）。所以抽到这里，谁都不许各写一份。
import type { Song } from './db';
import type { GenMeta } from './gens';

export type Srv = GenMeta['s'];

// 分区顺序（2026-10-24 主人重新定的口径）：
//   日服：全部 / 授权（Licensed）/ 原创（Original）
//   国服：全部 / 独占（Exclusive）/ KONAMI / 原创（Original）/ 流行（Popular）
// 英文只作对照，页面一律显示中文。
// 「授权」原名「版权」——主人指出「版权」词义不对（曲目的授权状态，不是版权归属）。
// 国服「独占」精确对应源表「华立独占」；「KONAMI」= 机种移植曲 + 国服旧框已有曲 432 首
// （后者由 catOf 按世代现算）；国服自己的音乐魔方曲按源生分类（Big Daddy 国服行属原创）。
export const CATS: Record<Srv, string[]> = {
  jp: ['授权', '原创'],
  cn: ['独占', 'KONAMI', '原创', '流行'],
};

// 分区归属（2026-10-24 主人三次修正后的最终口径）：
//   1) 不用「两服都有」自动改判（主人：「国服的 big daddy 属于原创分区」——
//      一首先按它自己的分类归属，不能由「另一个服有没有」倒推）；
//   2) 但「国服旧框已有曲」要全部移入 KONAMI（主人：「国服【原创】分类的旧框曲
//      全部移到【KONAMI】分区」）。
//   现在 category 列只存源生分类，分区由这里现算（不入库）。
//
// 【怎么认出「旧框曲」】不新增数据字段，用世代区分：
//   旧框已有曲是「国服已上线的日服曲」，祖宗在哪一代就是哪一代的 gen_name
//   （jubeat…beyond the Ave.）；而国服音乐魔方自己的曲（原创/流行/独占/移植）
//   世代一律是「音乐魔方」。实测：国服 524 行里 gen!=='音乐魔方' 的正好 433 行
//   = 旧框曲 432 + Big Daddy 日服行 1（那一行在国服视图里已被去重掉）。
//   所以 cn 视图下 gen!=='音乐魔方' ⇒ 旧框曲，归 KONAMI。
//
//   注意别和 Big Daddy 的国服行搞混：它的 gen 是「音乐魔方」，是国服自己的行，
//   按刚才第 1 条留在「原创」。
export const catOf = (s: Song, srv: Srv) =>
  srv === 'cn' && s.gen !== '音乐魔方' ? 'KONAMI' : s.cat;

// 视图归属：行 = 一份谱面记录，各归各的世代。双服曲（如 Big Daddy）两服各有一行，
// 国服视图只收「音乐魔方」世代的行，日服视图只收日服世代的行，避免同一首的两行串视图。
// 国服视图：cn=1 的所有行（2026-10-24 改）。
//   原来只收 gen==='音乐魔方' 的行，那是「国服独有曲」的口径；
//   加上「国服旧框已有曲」（sheet1 打√的 432 首，世代是日服世代）之后，
//   这批曲子在国服音乐魔方里也能玩，必须进国服视图、归 KONAMI 分区。
//   代价：国服视图的 KONAMI 分区会按日服世代再分块（jubeat…beyond the Ave.），
//   这是数据事实（它们确实首登于那些世代），不是 bug。
export const inView = (s: Song, srv: Srv) =>
  srv === 'cn' ? s.cn : s.jp && s.gen !== '音乐魔方';

// 跨服同曲的匹配键（2026-10-24）：国服视图要判「这首是不是已经有国服自己的行了」，
// 而两服 song_id 是两套体系（国服 9 位 9900/9910/9950 段，日服 8 位），只能按曲名+艺人比。
// **口径必须与 scripts/db/build-db.cjs 的 dualKey() 完全一致**——那边用它决定 server_jp/server_cn，
// 这边用它去重；两处不一致就会出现「数据说是同一首、页面当成两首」的鬼影。
// 改任何一边（小写化、去长押标记、去标点表）都要同步另一边。
export const songKey = (s: Song) =>
  String(s.t || '')
    .toLowerCase()
    .replace(/\[\s*2\s*\]/g, '')
    .replace(/\s+/g, '')
    .replace(/[～~—－・·!！?？'’“”「」『』()（）\[\]【】.,、\-]/g, '') +
  '|' +
  String(s.a || '')
    .toLowerCase()
    .replace(/\[\s*2\s*\]/g, '')
    .replace(/\s+/g, '')
    .replace(/[～~—－・·!！?？'’“”「」『』()（）\[\]【】.,、\-]/g, '');

// 世代页的归属：世代名本身就是精确归属（一个世代只属于一个服务器），
// 不必再过 inView 的服务器标志——否则「双服都有的那行」会在日服世代页里被漏掉。
export const inGen = (s: Song, gen: string) => s.gen === gen;
